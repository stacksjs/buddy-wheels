import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { click, launch, navigate, settle, waitFor } from '@stacksjs/testing/browser'

const origin = (process.env.BUDDY_QA_URL || 'http://localhost:3460').replace(/\/$/, '')
const browser = await launch()
const { cdp } = browser
const route = async (path: string) => navigate(cdp, `${origin}${path}`)
const text = (selector: string) => cdp.evaluate<string>(`document.querySelector(${JSON.stringify(selector)})?.textContent || ''`)
try {
  await route('/')
  await click(cdp, '.hero-copy a[href="/rover"]')
  await waitFor(() => cdp.evaluate("location.pathname === '/rover'"))
  await settle(cdp)
  await click(cdp, '.family-nav a[href="/shop"]')
  await waitFor(() => cdp.evaluate("location.pathname === '/shop'"))
  await settle(cdp)
  await click(cdp, '[data-size="L"]')
  await waitFor(async () => (await text('[data-product-price]')).includes('$264.50'))
  assert.match(await text('[data-product-name]'), /Buddy Large/)
  await click(cdp, '[data-stx-qty-inc]')
  assert.equal(await cdp.evaluate("document.querySelector('input[name=quantity]').value"), '2')
  await click(cdp, '#chair-purchase button[type=submit]')
  await waitFor(() => cdp.evaluate("location.pathname === '/cart'"))
  await settle(cdp)
  assert.match(await text('main'), /\$529\.00/)
  assert.equal((await text('[data-cart-count]')).trim(), '2')
  await click(cdp, '[data-stx-qty-dec]')
  await settle(cdp)
  await waitFor(() => cdp.evaluate("document.querySelector('input[name=quantity]')?.value === '1'"))
  assert.match(await text('main'), /\$264\.50/)
  assert.match(await text('.storefront-summary'), /Items total/)
  await click(cdp, 'a[href="/checkout"]')
  await waitFor(() => cdp.evaluate("location.pathname === '/checkout'"))
  await settle(cdp)
  await waitFor(async () => (await text('[data-launch-status]')).includes('Orders opening soon'))
  assert.equal(await cdp.evaluate("[...document.querySelectorAll('button')].find(button => button.textContent.includes('Ordering is not open')).disabled"), true)
  const denied = await fetch(`${origin}/api/checkout/place`, { method: 'POST' })
  assert.equal(denied.status, 409)
  assert.equal((await denied.json()).code, 'PRODUCT_VALIDATION_REQUIRED')
  const privateCookie = await cdp.send('Network.getCookies', { urls: [origin] }) as { cookies: Array<{ name: string, value: string }> }
  const cartCookie = privateCookie.cookies.find(cookie => cookie.name === 'stacks_cart')
  assert.ok(cartCookie)
  const cookieHeader = `stacks_cart=${cartCookie.value}`
  const unsigned = await fetch(`${origin}/api/cart`, { headers: { cookie: `stacks_cart=${cartCookie.value.split('.')[0]}` } })
  assert.equal((await unsigned.json()).items.length, 0)
  const addFour = await fetch(`${origin}/api/cart/add`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: cookieHeader }, body: JSON.stringify({ slug: 'buddy-large', quantity: 4 }) })
  assert.equal(addFour.status, 200)
  const overflow = await fetch(`${origin}/api/cart/add`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: cookieHeader }, body: JSON.stringify({ slug: 'buddy-large', quantity: 1 }) })
  assert.equal(overflow.status, 422)
  const bounded = await fetch(`${origin}/api/cart`, { headers: { cookie: cookieHeader } })
  const boundedBasket = await bounded.json()
  assert.equal(boundedBasket.items[0].qty, 5)
  const reset = await fetch(`${origin}/api/cart/update`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: cookieHeader }, body: JSON.stringify({ item_id: boundedBasket.items[0].id, quantity: 1 }) })
  assert.equal(reset.status, 200)
  const racingAdds = await Promise.all(Array.from({ length: 4 }, () => fetch(`${origin}/api/cart/add`, { method: 'POST', headers: { 'content-type': 'application/json', cookie: cookieHeader }, body: JSON.stringify({ slug: 'buddy-large', quantity: 2 }) })))
  assert.equal(racingAdds.filter(result => result.status === 200).length, 2)
  assert.equal(racingAdds.filter(result => result.status === 422).length, 2)
  const finalBasket = await (await fetch(`${origin}/api/cart`, { headers: { cookie: cookieHeader } })).json()
  assert.equal(finalBasket.items[0].qty, 5)
  const isolated = await fetch(`${origin}/api/cart`)
  assert.equal((await isolated.json()).items.length, 0)
  const forged = await fetch(`${origin}/api/cart`, { headers: { cookie: 'stacks_cart=tampered.invalid' } })
  assert.equal((await forged.json()).items.length, 0)
  const isolatedPage = await (await fetch(origin)).text()
  assert.match(isolatedPage, /data-cart-count[^>]*>\s*0\s*</)
  const badQuantity = await fetch(`${origin}/api/cart/add`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ slug: 'buddy-large', quantity: 1.5 }) })
  assert.equal(badQuantity.status, 422)
  const badRedirect = await fetch(`${origin}/api/cart/add`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ slug: 'buddy-large', quantity: 1, redirect: 'https://example.com' }) })
  assert.equal(badRedirect.status, 422)
  await route('/rover?mode=snow')
  assert.equal(await cdp.evaluate("document.querySelector('meta[property=\"og:image\"]').content"), 'https://buddywheels.org/images/buddy-rover.webp')
  await waitFor(async () => (await text('[data-rover-price]')).includes('$1,099.00'))
  assert.equal(await cdp.evaluate("document.querySelector('.rover-photo img').getAttribute('src')"), '/images/buddy-rover-snow.webp')
  for (const [mode, price] of [['run', '$999.00'], ['coast', '$1,049.00'], ['all-season', '$1,199.00'], ['snow', '$1,099.00'], ['coast', '$1,049.00']]) {
    await click(cdp, `[data-mode="${mode}"]`)
    await waitFor(async () => (await text('[data-rover-price]')).includes(price))
  }
  await click(cdp, '#rover-purchase button[type=submit]')
  await waitFor(() => cdp.evaluate("location.pathname === '/cart'"))
  await settle(cdp)
  assert.match(await text('main'), /\$1,771\.50/)
  assert.equal(await cdp.evaluate("document.querySelector('[data-basket-line=buddy-rover-coast] img').getAttribute('src')"), '/images/buddy-rover-640.webp')
  await click(cdp, '[data-basket-line=buddy-rover-coast] button[type=submit].button-text')
  await settle(cdp)
  await waitFor(() => cdp.evaluate("!document.querySelector('[data-basket-line=buddy-rover-coast]')"))
  await cdp.send('Emulation.setDeviceMetricsOverride', { width: 320, height: 850, deviceScaleFactor: 1, mobile: true })
  await route('/rover?mode=snow')
  await click(cdp, '#rover-mobile-add')
  await waitFor(() => cdp.evaluate("location.pathname === '/cart'"))
  await settle(cdp)
  assert.match(await text('main'), /Buddy Rover \/ Snow/)
  await cdp.send('Emulation.clearDeviceMetricsOverride')
  await route('/fit-guide')
  for (const [selector, value] of [['#weight', '50'], ['#height', '12']]) {
    await cdp.evaluate(`(() => { const input = document.querySelector(${JSON.stringify(selector)}); input.value = ${JSON.stringify(value)}; input.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  }
  await click(cdp, 'button[type=submit]')
  await waitFor(async () => (await text('[data-fit-result]')).includes('(M)'))
  assert.match(await text('[data-fit-result]'), /not a fit approval/)
  await mkdir('storage/framework/runtime/qa', { recursive: true })
  await route('/')
  assert.equal(await cdp.evaluate("document.querySelectorAll('a[href=\"/shop?size=L\"]').length > 0"), true, 'Native product card links to the size configurator')
  for (const width of [320, 428, 768, 1440]) {
    await cdp.send('Emulation.setDeviceMetricsOverride', { width, height: 1000, deviceScaleFactor: 1, mobile: width < 768 })
    await route('/')
    const overflow = await cdp.evaluate<number>(`Math.max(0, document.documentElement.scrollWidth - ${width})`)
    assert.equal(overflow, 0, `Horizontal overflow at ${width}px`)
    if (width >= 768) {
      const alignment = await cdp.evaluate<{ cta: number[], icons: number[], headings: number[] }>(`(() => ({ cta: [...document.querySelectorAll('.hero-copy > .flex > a')].map(el => { const r = el.getBoundingClientRect(); return r.top + r.height / 2 }), icons: [...document.querySelectorAll('.principles > div > i')].map(el => el.getBoundingClientRect().top), headings: [...document.querySelectorAll('.principles h2')].map(el => el.getBoundingClientRect().top) }))()`)
      assert.ok(Math.abs(alignment.cta[0]! - alignment.cta[1]!) < 1, `Hero CTA alignment at ${width}px`)
      assert.ok(Math.max(...alignment.icons) - Math.min(...alignment.icons) < 1, `Icon alignment at ${width}px`)
      assert.ok(Math.max(...alignment.headings) - Math.min(...alignment.headings) < 1, `Heading alignment at ${width}px`)
    }
    const screenshot = await cdp.send('Page.captureScreenshot', { format: 'png' }) as { data: string }
    await Bun.write(`storage/framework/runtime/qa/home-${width}.png`, Buffer.from(screenshot.data, 'base64'))
    for (const path of ['/shop', '/rover', '/cart', '/checkout', '/fit-guide', '/our-story', '/care', '/policies', '/journal']) {
      await route(path)
      assert.equal(await cdp.evaluate<number>(`Math.max(0, document.documentElement.scrollWidth - ${width})`), 0, `Horizontal overflow on ${path} at ${width}px`)
      if (path === '/rover') {
        if (width >= 768)
          assert.equal(await cdp.evaluate("getComputedStyle(document.querySelector('#rover-purchase button[type=submit]')).backgroundColor"), 'rgb(35, 75, 56)')
        const productShot = await cdp.send('Page.captureScreenshot', { format: 'png' }) as { data: string }
        await Bun.write(`storage/framework/runtime/qa/rover-${width}.png`, Buffer.from(productShot.data, 'base64'))
      }
    }
  }
  assert.deepEqual(cdp.errors, [])
  console.log(JSON.stringify({ origin, shoppingJourney: 'passed', roverConfigurations: 'passed', mixedBasket: 'passed', mobilePurchase: 'passed', checkoutGate: 'passed', cartIsolation: 'passed', quantityValidation: 'passed', fitPlanner: 'passed', responsiveWidths: [320, 428, 768, 1440], consoleErrors: [] }, null, 2))
}
finally {
  await browser.close()
}
